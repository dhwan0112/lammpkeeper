def test_slab_shell_load_orders_and_shared_reads_preserve_analytic_answers():
    """The same serialized reference drives metadata, shared jobs and cached jobs."""
    from lammps_post.shell import LammpsPostShell
    with tempfile.TemporaryDirectory() as tmp:
        dump, metadata = slab.generate(Path(tmp) / 'source with spaces')
        for order in (('input', 'dump'), ('dump', 'input')):
            for cache_mb in (0, 4):
                shell = LammpsPostShell()
                shell.noninteractive = True
                shell.state.output_dir = str(Path(tmp) / 'output')
                for kind in order:
                    path = metadata if kind == 'input' else dump
                    extra = f' --cache-mb {cache_mb}' if kind == 'dump' else ''
                    _quiet(lambda: shell.do_load(f'{kind} {shlex.quote(str(path))}{extra}'))
                _quiet(lambda: shell.do_set('surface_z 8'))
                assert shell.state.pbc == (True, True, False)
                assert shell.state.dt_fs == 1.
                # Observe rather than replace the shared executor; all real work
                # must complete and yield independent expected numerical answers.
                with patch.object(shell, '_run_jobs_shared', wraps=shell._run_jobs_shared) as shared:
                    _quiet(shell._analyze_all)
                    assert shared.call_count == (1 if cache_mb == 0 else 0)
                _quiet(lambda: shell._analyze_msd(['--species', 'O'], _batch=True))
                _quiet(lambda: shell._analyze_rdf(['O-O', '--frames', '6'], _batch=True))
                cache = shell.state.cache
                np.testing.assert_allclose(cache['msd_Fe']['msd'], 0.)
                np.testing.assert_allclose(cache['msd_O']['msd'], O_MSD, atol=1e-12)
                np.testing.assert_allclose(cache['msd_O']['time'], TIME_PS)
                np.testing.assert_array_equal(cache['oar']['n_absorbed'], [2, 1, 2, 2, 3, 2])
                np.testing.assert_array_equal(cache['penetration']['n_adsorbed'], [2, 1, 2, 1, 3, 2])
                np.testing.assert_array_equal(cache['dissociation']['n_o2'], np.full(6, 2))
                frames, ci = _read(dump)
                # Shell uses public default radius/bins, not the eight-bin API
                # case above; its own actual grid is checked with a fresh oracle.
                np.testing.assert_allclose(cache['rdf_O-O']['g'], _rdf_oracle(frames, ci, 6., 200))


def test_slab_native_and_numpy_match_every_reader_access_path():
    """Successful compiled calls, not silent fallback, establish native coverage."""
    _util.require(p._native is not None, 'native parser unavailable or disabled (slab parity)')
    with tempfile.TemporaryDirectory() as tmp:
        dump, _input = slab.generate(tmp)
        baseline = None
        for native in (False, True):
            for mode in ('stream', 'index', 'cached', 'uncached'):
                reader = p.DumpReader(dump)
                calls = []
                native_module = p._native

                def observe(*args, **kwargs):
                    """Record only successfully returned native atom blocks."""
                    result = native_module.parse_block(*args, **kwargs)
                    assert result[2] == args[1], 'native atom count must match the requested block'
                    calls.append(True)
                    return result

                reader._native = SimpleNamespace(parse_block=observe) if native else None
                # A native result may be rejected and retried through loadtxt;
                # recording calls alone would falsely certify that fallback.
                guard = (patch.object(p.np, 'loadtxt', side_effect=AssertionError('unexpected NumPy fallback'))
                         if native else contextlib.nullcontext())
                with guard:
                    if mode == 'stream':
                        frames = list(reader)
                    elif mode == 'index':
                        index = reader.index()
                        frames = [reader.read_frame(index, k) for k in range(len(index))]
                    else:
                        frames = list(p.LazyFrames(reader, cache_bytes=10**6 if mode == 'cached' else 0))
                assert reader.boundary == ('pp', 'pp', 'ff')
                assert len(frames) == 6
                if native:
                    assert len(calls) >= 6, 'NumPy fallback cannot certify native parsing'
                if baseline is None:
                    baseline = frames
                for expected, observed in zip(baseline, frames):
                    np.testing.assert_array_equal(observed['atoms'], expected['atoms'])
                    np.testing.assert_array_equal(observed['elements'], expected['elements'])
                    np.testing.assert_array_equal(observed['box'], expected['box'])
                    assert observed['timestep'] == expected['timestep']


