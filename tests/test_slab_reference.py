def test_slab_profile_and_curves_render_without_false_half_uptake():
    """Real saved figures show three of eight initial O crossing, never a t50."""
    from lammps_post import plotting as plot
    _util.require(plot.HAS_MPL, 'matplotlib not installed (slab reference rendering)')
    with tempfile.TemporaryDirectory() as tmp:
        dump, _input = slab.generate(Path(tmp) / 'source')
        frames, ci = _read(dump)
        profile = a.analyze_penetration_profile(frames, ci, dt_fs=1., o_type=2, fe_type=1)
        captured = {}
        inspected = set()
        original_save = plot._save_fig

        def capture(fig, outpath, dpi=150, save_format=None):
            """Inspect actual artists before invoking the production PNG writer."""
            if Path(outpath).name == 'o_adsorption_timeline.png':
                ax = fig.axes[0]
                captured['title'] = ax.get_title()
                captured['annotations'] = [text.get_text() for text in ax.texts]
                np.testing.assert_allclose(ax.lines[0].get_xdata(), [0., 0., .03])
                np.testing.assert_array_equal(ax.lines[0].get_ydata(), [1, 2, 3])
                inspected.add('o_adsorption_timeline.png')
            elif Path(outpath).name == 'msd_O.png':
                np.testing.assert_allclose(fig.axes[0].lines[0].get_xdata(), TIME_PS)
                np.testing.assert_allclose(fig.axes[0].lines[0].get_ydata(), O_MSD, atol=1e-12)
                inspected.add('msd_O.png')
            elif Path(outpath).name == 'rdf_O_O.png':
                np.testing.assert_allclose(fig.axes[0].lines[0].get_ydata(),
                                           _rdf_oracle(frames, ci, 3., 8))
                inspected.add('rdf_O_O.png')
            return original_save(fig, outpath, dpi=dpi, save_format=save_format)

        output = Path(tmp) / 'plots'
        output.mkdir()
        with patch.object(plot, '_save_fig', side_effect=capture):
            plot.plot_penetration_profile(profile, str(output), dpi=40, n_snapshots=3)
            plot.plot_msd(a.analyze_msd(frames, ci, species_type=2, dt_fs=1., pbc=slab.PBC),
                          'O', str(output), dpi=40)
            plot.plot_rdf(a.compute_rdf(frames, ci, 2, 2, r_max=3., n_bins=8,
                                        pbc=slab.PBC, label_a='O', label_b='O'), str(output), dpi=40)
        assert inspected == {'o_adsorption_timeline.png', 'msd_O.png', 'rdf_O_O.png'}
        assert '3/8 initial O' in captured['title']
        assert not any('t₅₀' in text for text in captured['annotations'])
        pngs = list(output.glob('*.png'))
        assert {path.name for path in pngs} == {
            'o_trajectories.png', 'o_kymograph.png', 'o_zdist_evolution.png',
            'o_adsorption_timeline.png', 'o_penetration_3d.png',
            'o_penetration_metrics.png', 'msd_O.png', 'rdf_O_O.png'}
        for path in pngs:
            assert path.read_bytes()[:8] == bytes.fromhex('89504e470d0a1a0a')
            assert path.stat().st_size > 1000
