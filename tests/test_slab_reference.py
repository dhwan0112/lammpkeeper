"""TEST-3: one serialized, analytic pp/pp/ff system across the post pipeline.

The stdlib generator is test data, not an equilibrated Fe crystal, a real LAMMPS
run, a diffusion measurement or the undecided non-Fe GEN-8 reference. ID 108's
39-Angstrom jump deliberately makes accidental z unwrapping observable. Expected
values below are derived independently of production MIC/neighbor routines.
Force-field inference/spin outputs are not oracles here: dump-only guesses are
still warned, and removing those heuristics remains the separate GEN-2 item.
"""
