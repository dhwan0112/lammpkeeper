TIME_PS = np.arange(6) * .01
O_MSD = (4.5 * np.arange(6)**2 + 1521 * (np.arange(6) % 2)) / 8


def _read(path):
    """Read serialized coordinates; no analysis uses generator's in-memory rows."""
    frames, _columns, col_idx = p.parse_dump(path)
    return frames, col_idx


def _image_pairs(frame, col_idx, pbc=(True, True, False)):
    """Enumerate one nearest image per unordered O pair without production MIC.

    Slab periodicity permits nine x/y translations and exactly zero z shift.
    Taking the minimum first avoids counting repeated images as separate atoms.
    This small oracle intentionally trades speed for transparent geometry.
    """
    rows = frame['atoms']
    oxygen = rows[rows[:, col_idx['type']] == 2]
    ids = oxygen[:, col_idx['id']].astype(int)
    xyz = oxygen[:, [col_idx[c] for c in ('x', 'y', 'z')]]
    lengths = np.diff(frame['box'], axis=1).ravel()
    shifts = [np.asarray(image) * lengths for image in itertools.product(
        *((-1, 0, 1) if periodic else (0,) for periodic in pbc))]
    pairs = []
    for i in range(len(oxygen) - 1):
        for j in range(i + 1, len(oxygen)):
            distance = min(float(np.linalg.norm(xyz[j] + shift - xyz[i])) for shift in shifts)
            pairs.append((distance, min(ids[i], ids[j]), max(ids[i], ids[j])))
    return sorted(pairs)


def _rdf_oracle(frames, col_idx, r_max, n_bins):
    """Count both directions of each physical pair and normalize each frame.

    The density convention is N/V, so a same-species histogram is already
    ordered and receives no extra factor of two after normalization.
    """
    edges = np.linspace(0, r_max, n_bins + 1)
    shell_volume = 4 * np.pi / 3 * np.diff(edges**3)
    curves = []
    for frame in frames:
        distances = [distance for distance, _left, _right in _image_pairs(frame, col_idx)
                     if 0 < distance < r_max]
        histogram, _ = np.histogram(distances, bins=edges)
        volume = float(np.prod(np.diff(frame['box'], axis=1)))
        curves.append(2 * histogram / (8 * (8 / volume) * shell_volume))
    return np.mean(curves, axis=0)


def _quiet(call):
    """Silence presentation output, preserving all exceptions and warnings."""
    with contextlib.redirect_stdout(io.StringIO()):
        return call()


def test_slab_generator_is_small_reproducible_and_standalone():
    """Generated bytes and metadata are stable, even under a stdlib-only CLI."""
    assert slab.BOX == ((0., 20.), (0., 20.), (0., 40.))
    assert slab.PBC == (True, True, False) and slab.STEPS == (0, 10, 20, 30, 40, 50)
    assert slab.DT_FS == 1. and slab.SURFACE_Z == 8.
    with tempfile.TemporaryDirectory(prefix='lkpr-slab-') as tmp:
        root = Path(tmp)
        first = slab.generate(root / 'first')
        second = slab.generate(root / 'second')
        assert [path.read_bytes() for path in first] == [path.read_bytes() for path in second]
        output = root / 'CLI output with spaces'
        run = subprocess.run([sys.executable, '-S', str(Path(slab.__file__)), str(output)],
                             capture_output=True, text=True, timeout=20)
        assert run.returncode == 0, run.stdout + run.stderr
        assert (output / 'slab.dump').read_bytes() == first[0].read_bytes()
        frames, ci = _read(first[0])
        assert len(frames) == 6 <= 20
        assert all(frame['natoms'] == 16 <= 200 for frame in frames)
        assert ci == {'id': 0, 'type': 1, 'x': 2, 'y': 3, 'z': 4}
        assert p.DumpReader(first[0]).boundary == ('pp', 'pp', 'ff')
        assert p.parse_input(first[1])['dt_fs'] == 1.0
        for frame in frames:
            np.testing.assert_array_equal(frame['box'], [[0, 20], [0, 20], [0, 40]])
            assert set(frame['atoms'][:, ci['id']]) == set(range(1, 9)) | set(range(101, 109))
            assert set(frame['elements']) == {'Fe', 'O'}
        # Permuted rows make identity-based tracking a genuine requirement.
        assert not np.array_equal(frames[0]['atoms'][:, 0], frames[1]['atoms'][:, 0])


def test_slab_msd_tracks_ids_and_never_folds_nonperiodic_z():
    """Two x movers, two y movers, adsorption and the wall probe give exact MSD."""
    with tempfile.TemporaryDirectory() as tmp:
        dump, _input = slab.generate(tmp)
        frames, ci = _read(dump)
        oxygen = a.analyze_msd(frames, ci, species_type=2, dt_fs=1., pbc=(True, True, False))
        iron = a.analyze_msd(frames, ci, species_type=1, dt_fs=1., pbc=(True, True, False))
        np.testing.assert_allclose(oxygen['time'], TIME_PS)
        np.testing.assert_allclose(oxygen['msd'], O_MSD, rtol=1e-13, atol=1e-12)
        np.testing.assert_array_equal(iron['msd'], np.zeros(6))
        # A deliberately different periodic box interpretation must change the
        # answer; this proves the slab test is sensitive to the z boundary flag.
        bulk = a.analyze_msd(frames, ci, species_type=2, dt_fs=1., pbc=(True, True, True))
        expected_bulk = (4.5 * np.arange(6)**2 + np.arange(6) % 2) / 8
        np.testing.assert_allclose(bulk['msd'], expected_bulk, atol=1e-12)
        assert not np.allclose(bulk['msd'], oxygen['msd'])


def test_slab_o2_pairs_match_independent_images_and_exclude_z_images():
    """Both lateral boundary pairs survive; opposite z faces are not neighbors."""
    with tempfile.TemporaryDirectory() as tmp:
        dump, _input = slab.generate(tmp)
        frames, ci = _read(dump)
        for frame in frames:
            used, assigned = set(), set()
            for distance, left, right in _image_pairs(frame, ci):
                if distance < 1.8 and left not in used and right not in used:
                    used.update((left, right))
                    assigned.add((left, right))
            assert assigned == {(101, 102), (103, 104)}
        result = a.detect_o2_dissociation(frames, ci, o_type=2, dt_fs=1., pbc=(True, True, False))
        np.testing.assert_array_equal(result['n_o2'], np.full(6, 2))
        np.testing.assert_array_equal(result['n_dissociated'], np.full(6, 4))
        np.testing.assert_allclose(result['frac_in_o2'], .5)
        np.testing.assert_allclose(result['frac_dissociated'], .5)
        np.testing.assert_allclose(result['time'], TIME_PS)
        bulk = a.detect_o2_dissociation(frames, ci, o_type=2, pbc=(True, True, True))
        np.testing.assert_array_equal(bulk['n_o2'], np.full(6, 3))


def test_slab_rdf_has_only_the_enumerated_ordered_pair_bin():
    """Four distance-one contributions occupy [.75,1.125), with known N/V."""
    with tempfile.TemporaryDirectory() as tmp:
        dump, _input = slab.generate(tmp)
        frames, ci = _read(dump)
        result = a.compute_rdf(frames, ci, 2, 2, r_max=3., n_bins=8, max_frames=6,
                               pbc=(True, True, False), label_a='O', label_b='O')
        expected = np.zeros(8)
        expected[2] = 1000 / ((4 * np.pi / 3) * (1.125**3 - .75**3))
        np.testing.assert_allclose(result['g'], expected, rtol=1e-13, atol=1e-13)
        np.testing.assert_allclose(result['g'], _rdf_oracle(frames, ci, 3., 8))
        assert result['n_frames'] == 6


def test_slab_rdf_real_tree_matches_forced_fallback():
    """Candidate acceleration actually runs before comparing its curve to fallback."""
    with tempfile.TemporaryDirectory() as tmp:
        dump, _input = slab.generate(tmp)
        frames, ci = _read(dump)
        actual = a._rdf_candidate_pairs
        observed = []

        def observe(*args, **kwargs):
            """Record real candidate availability without changing nominations."""
            result = actual(*args, **kwargs)
            observed.append(result is not None)
            return result

        with patch.object(a, '_rdf_candidate_pairs', side_effect=observe):
            fast = a.compute_rdf(frames, ci, 2, 2, r_max=3., n_bins=8, pbc=slab.PBC)
        _util.require(any(observed), 'scipy unavailable: real accelerated slab RDF not verified')
