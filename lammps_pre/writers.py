"""
File writers for lammps-pre.

Generates LAMMPS data files, region include files, and XYZ visualization files.
"""

import os

from lammps_pre import VERSION
from lammps_pre.display import progress_msg, C


# ═══════════════════════════════════════════════════════════════
# LAMMPS Data File
# ═══════════════════════════════════════════════════════════════

def write_data_file(build, state, filepath):
    """
    Write LAMMPS data file.

    Format depends on force field:
      - ReaxFF: atom_style charge (id type q x y z), q=0.0
      - ACE:    atom_style atomic (id type x y z), spin encoding
    """
    ff = state.ff
    fe_pos = build.fe_positions
    o2_pos = build.o2_positions
    n_fe = len(fe_pos)
    n_o = len(o2_pos)
    n_total = n_fe + n_o
    regions = build.regions

    xlo, xhi, ylo, yhi, zlo, zhi = build.box
    atom_types = ff['atom_types']
    n_types = len(atom_types)
    masses = ff['masses']

    with open(filepath, 'w') as f:
        # Header
        f.write(f"# Generated by lammps-pre v{VERSION}\n")
        f.write(f"# Force field: {ff['label']} | Surface: Fe({state.surface})\n")
        f.write(f"# Slab: {state.nx}x{state.ny}x{state.nz} layers "
                f"(fixed {regions['n_fixed_layers']} / "
                f"NVT {regions['n_thermostat_layers']} / "
                f"NVE {regions['n_nve_layers']})\n")
        f.write(f"# Atoms: {n_fe} Fe + {n_o} O = {n_total}\n\n")

        f.write(f"{n_total} atoms\n")
        f.write(f"{n_types} atom types\n\n")

        f.write(f"{xlo:.10f} {xhi:.10f} xlo xhi\n")
        f.write(f"{ylo:.10f} {yhi:.10f} ylo yhi\n")
        f.write(f"{zlo:.10f} {zhi:.10f} zlo zhi\n\n")

        # Masses
        f.write("Masses\n\n")
        for tid, mass in sorted(masses.items()):
            label = atom_types.get(tid, '')
            f.write(f"{tid} {mass}  # {label}\n")
        f.write("\n")

        # Atoms section
        if ff['atom_style'] == 'charge':
            f.write("Atoms # charge\n\n")
            for i, pos in enumerate(fe_pos, 1):
                f.write(f"{i:8d} 1 0.0 {pos[0]:16.8f} {pos[1]:16.8f} "
                        f"{pos[2]:16.8f}\n")
            for j, pos in enumerate(o2_pos):
                idx = n_fe + j + 1
                f.write(f"{idx:8d} 2 0.0 {pos[0]:16.8f} {pos[1]:16.8f} "
                        f"{pos[2]:16.8f}\n")
        else:
            # atom_style atomic (ACE)
            f.write("Atoms # atomic\n\n")
            # All Fe start as type 1 (Fe_up); spin assignment is done in input script
            for i, pos in enumerate(fe_pos, 1):
                f.write(f"{i:8d} 1 {pos[0]:16.8f} {pos[1]:16.8f} "
                        f"{pos[2]:16.8f}\n")
            for j, pos in enumerate(o2_pos):
                idx = n_fe + j + 1
                o_type = 3  # O is type 3 in ACE
                f.write(f"{idx:8d} {o_type} {pos[0]:16.8f} {pos[1]:16.8f} "
                        f"{pos[2]:16.8f}\n")

    progress_msg(f"Saved: {C.ok(filepath)} ({n_total} atoms, {n_types} types)")


# ═══════════════════════════════════════════════════════════════
# Region Include File
# ═══════════════════════════════════════════════════════════════

def write_regions_inc(build, state, filepath):
    """Write LAMMPS variable include file for region boundaries."""
    regions = build.regions

    with open(filepath, 'w') as f:
        f.write(f"# Region boundaries — auto-generated by lammps-pre v{VERSION}\n")
        f.write(f"# Force field: {state.ff['label']} | Surface: Fe({state.surface})\n")
        f.write(f"# {regions['n_layers']} layers: "
                f"fixed {regions['n_fixed_layers']} / "
                f"NVT {regions['n_thermostat_layers']} / "
                f"NVE {regions['n_nve_layers']}\n\n")
        f.write(f"variable z_fixed_top     equal {regions['z_fixed_top']:.4f}\n")
        f.write(f"variable z_lower_nvt_top equal {regions['z_lower_nvt_top']:.4f}\n")
        f.write(f"variable z_nve_top       equal {regions['z_nve_top']:.4f}\n")
        f.write(f"variable z_wall_lower    equal {regions['z_wall_lower']:.4f}\n")

    progress_msg(f"Saved: {C.ok(filepath)} (4 region variables)")


# ═══════════════════════════════════════════════════════════════
# XYZ Visualization File
# ═══════════════════════════════════════════════════════════════

def write_xyz(build, filepath):
    """Write XYZ file for visualization (e.g., OVITO, VMD)."""
    fe_pos = build.fe_positions
    o2_pos = build.o2_positions
    n_total = len(fe_pos) + len(o2_pos)

    with open(filepath, 'w') as f:
        f.write(f"{n_total}\n")
        f.write(f"Fe slab + {len(o2_pos) // 2} O2 "
                f"(generated by lammps-pre v{VERSION})\n")
        for pos in fe_pos:
            f.write(f"Fe {pos[0]:16.8f} {pos[1]:16.8f} {pos[2]:16.8f}\n")
        for pos in o2_pos:
            f.write(f"O  {pos[0]:16.8f} {pos[1]:16.8f} {pos[2]:16.8f}\n")

    progress_msg(f"Saved: {C.ok(filepath)} ({n_total} atoms)")


# ═══════════════════════════════════════════════════════════════
