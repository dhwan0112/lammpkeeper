def get_filenames(state):
    """Return dict of output filenames based on force field."""
    ff_name = state.forcefield
    if ff_name == 'ace':
        return {
            'data': 'lammps_ace.data',
            'regions': 'regions_ace.inc',
            'input': 'ace_oxidation.in',
            'runscript': 'run.sh',
            'xyz': 'structure.xyz',
        }
    else:
        return {
            'data': 'lammps.data',
            'regions': 'regions.inc',
            'input': 'reaxff_oxidation.in',
            'runscript': 'run.sh',
            'xyz': 'structure.xyz',
        }


def write_input_script(build, state, filepath):
    """Write LAMMPS input script using force-field-specific template."""
    from lammps_pre.templates import render_input_script
    content = render_input_script(build, state)
    with open(filepath, 'w') as f:
        f.write(content)
    ff = state.ff
    stages = '4-stage' if state.has_spin else '3-stage'
    progress_msg(f"Saved: {C.ok(filepath)} ({ff['label']} {stages} protocol)")


def write_run_script(build, state, filepath):
    """Write PBS job submission script."""
    from lammps_pre.templates import render_run_script
    content = render_run_script(build, state)
    with open(filepath, 'w') as f:
        f.write(content)
    os.chmod(filepath, 0o755)
    progress_msg(f"Saved: {C.ok(filepath)} (PBS, {state.get_ncpus()} cores, "
                 f"{state.get_walltime_hr()} hr)")


def write_all(build, state, directory=None):
    """Write all output files to directory."""
    d = directory or state.output_dir
    os.makedirs(d, exist_ok=True)

    names = get_filenames(state)

    write_data_file(build, state, os.path.join(d, names['data']))
    write_regions_inc(build, state, os.path.join(d, names['regions']))
    write_input_script(build, state, os.path.join(d, names['input']))
    write_run_script(build, state, os.path.join(d, names['runscript']))
    write_xyz(build, os.path.join(d, names['xyz']))

    print(f"\n  {C.ok('All files saved to:')} {os.path.abspath(d)}/")
