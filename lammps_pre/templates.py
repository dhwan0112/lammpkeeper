"""
LAMMPS input script and PBS run script templates.

Renders force-field-specific input scripts from PreState parameters.
Templates reproduce the exact structure of the production atlas scripts.
"""

from lammps_pre import VERSION
from lammps_pre.writers import get_filenames
from lammpkeeper.common.mapping import element_order


# ═══════════════════════════════════════════════════════════════
# Input Script Renderer
# ═══════════════════════════════════════════════════════════════

def render_input_script(build, state):
    """Dispatch to force-field-specific template."""
    ff = state.forcefield
    if ff == 'ace':
        return _render_ace(build, state)
    elif ff in ('reaxff2010', 'reaxff2015'):
        return _render_reaxff(build, state)
    else:
        raise ValueError(f"No template for force field: {ff}")


def _render_ace(build, state):
    """ACE input script: 4-stage (spin eq -> minimize -> eq -> oxidation)."""
    s = state
    ff = s.ff
    names = get_filenames(s)
    # Same element order as pair_coeff, straight from the shared mapping. Written
    # into every dump so the Fe_up/Fe_down/O convention travels with the file.
    elements = ' '.join(element_order('ace'))

    return f"""\
# ===================================================================
# Fe Slab + O2 Oxidation — ACE
# Generated by lammps-pre v{VERSION}
# ===================================================================
#
# Usage:
#   lmp -var T {s.temperature} -var SEED {s.velocity_seed} -in {names['input']}
#
# Potential: {ff['reference']}
#
# Type mapping (Ising spin encoding):
#   Type 1 (Fe) = Fe_up   (spin up)
#   Type 2 (Mn) = Fe_down (spin down)  [mass = 55.845]
#   Type 3 (O)  = O
# ===================================================================

# --- Default variables (overridable via command line) ---
variable        T        index {s.temperature}
variable        SEED     index {s.velocity_seed}
variable        SPIN_PS  index {s.get_spin_ps()}
variable        EQ_PS    index {s.get_eq_ps()}
variable        OX_PS    index {s.get_ox_ps()}
variable        MC_EVERY index {s.mc_every}
variable        MC_N     index {s.mc_n}
variable        NPROC_X  index {ff.get('nproc_x') or 6}
variable        NPROC_Y  index {ff.get('nproc_y') or 8}

# --- Derived variables ---
variable        dt        equal {ff['dt']}
variable        T_damp    equal {ff['T_damp']}
variable        spin_steps equal round(${{SPIN_PS}}/${{dt}})
variable        eq_steps   equal round(${{EQ_PS}}/${{dt}})
variable        ox_steps   equal round(${{OX_PS}}/${{dt}})
variable        ox_dense   equal round(50.0/${{dt}})
variable        ox_remain  equal round((${{OX_PS}}-50.0)/${{dt}})

variable        label     string ace_${{T}}K

# ===================================================================
# Basic Settings
# ===================================================================
units           metal
atom_style      atomic
boundary        {s.boundary}
processors      ${{NPROC_X}} ${{NPROC_Y}} 1
read_data       {names['data']}

# --- Spin initialization: fixed layer = all Fe_down, mobile = 50/50 ---
set             type 1 type/fraction 2 1.0 12345

# --- ACE potential ---
pair_style      {ff['pair_style']}
pair_coeff      {ff['pair_coeff']}

neighbor        2.0 bin
neigh_modify    every 1 delay 0 check yes

# ===================================================================
# Region Definitions
# ===================================================================
include         {names['regions']}

region          r_fixed block INF INF INF INF INF ${{z_fixed_top}}
group           g_fixed region r_fixed
group           g_mobile subtract all g_fixed

group           g_fe      type 1 2
group           g_o       type 3

region          r_lower_nvt block INF INF INF INF ${{z_fixed_top}} ${{z_lower_nvt_top}}
region          r_nve block INF INF INF INF ${{z_lower_nvt_top}} ${{z_nve_top}}
region          r_upper_nvt block INF INF INF INF ${{z_wall_lower}} INF

group           g_lower_nvt region r_lower_nvt
group           g_nve region r_nve
group           g_upper_nvt region r_upper_nvt

# --- Restore mobile Fe to 50/50 spin ---
group           g_fe_mobile intersect g_fe g_mobile
set             group g_fe_mobile type/fraction 1 0.5 48271

# --- Walls ---
fix             wall_upper all wall/reflect zhi EDGE
fix             wall_lower_o g_o wall/reflect zlo v_z_wall_lower

# --- Frozen layer ---
velocity        g_fixed set 0.0 0.0 0.0
fix             freeze g_fixed setforce 0.0 0.0 0.0

# --- MC spin swap ---
fix             mc_spin g_fe_mobile atom/swap ${{MC_EVERY}} ${{MC_N}} 482793 ${{T}} &
                semi-grand yes types 1 2 mu 0.0 0.0

# --- Diagnostics ---
compute         temp_mobile g_mobile temp
compute         o_z g_o property/atom z
compute         o_z_min g_o reduce min c_o_z
compute         o_z_max g_o reduce max c_o_z

# --- Output ---
thermo          {s.get_thermo_interval()}
thermo_style    custom {ff['thermo_fields']}
thermo_modify   temp temp_mobile
log             ${{label}}.log

dump            traj all custom {s.get_dump_interval()} traj_${{label}}.lammpstrj &
                {ff['dump_fields']}
dump_modify     traj sort id element {elements} format float %12.6f

# ===================================================================
# Stage 0: Spin Equilibration (${{SPIN_PS}} ps)
# ===================================================================
print "========== Stage 0: Spin Equilibration (${{SPIN_PS}} ps at ${{T}} K) =========="
timestep        ${{dt}}
velocity        g_mobile create ${{T}} 98765 dist gaussian

fix             nvt_lower g_lower_nvt nvt temp ${{T}} ${{T}} ${{T_damp}}
fix             nve_middle g_nve nve
fix             nvt_upper g_upper_nvt nvt temp ${{T}} ${{T}} ${{T_damp}}

run             ${{spin_steps}}

print "========== Spin Eq Complete =========="

# ===================================================================
# Stage 1: Energy Minimization
# ===================================================================
print "========== Stage 1: Energy Minimization =========="
unfix           nvt_lower
unfix           nve_middle
unfix           nvt_upper

min_style       cg
minimize        {ff['min_etol']:.0e} {ff['min_ftol']:.0e} {ff['min_maxiter']} {ff['min_maxeval']}

# ===================================================================
# Stage 2: Equilibration (${{EQ_PS}} ps)
# ===================================================================
print "========== Stage 2: Equilibration (${{EQ_PS}} ps at ${{T}} K) =========="
timestep        ${{dt}}
velocity        g_mobile create ${{T}} ${{SEED}} dist gaussian

fix             nvt_lower g_lower_nvt nvt temp ${{T}} ${{T}} ${{T_damp}}
fix             nve_middle g_nve nve
fix             nvt_upper g_upper_nvt nvt temp ${{T}} ${{T}} ${{T_damp}}

run             ${{eq_steps}}

# ===================================================================
# Stage 3: Oxidation (${{OX_PS}} ps)
# ===================================================================
print "========== Stage 3: Oxidation (${{OX_PS}} ps at ${{T}} K) =========="

# 3a: First 50 ps — dense dump ({s.dump_dense_interval} steps)
undump          traj
dump            traj_ox all custom {s.dump_dense_interval} traj_oxidation_${{label}}.lammpstrj &
                {ff['dump_fields']}
dump_modify     traj_ox sort id element {elements} format float %12.6f

unfix           wall_lower_o
run             ${{ox_dense}}

# 3b: Remaining time — standard dump ({s.get_dump_interval()} steps)
undump          traj_ox
dump            traj_ox2 all custom {s.get_dump_interval()} traj_oxidation_${{label}}.lammpstrj &
                {ff['dump_fields']}
dump_modify     traj_ox2 sort id element {elements} format float %12.6f append yes

run             ${{ox_remain}}

# ===================================================================
# Save
# ===================================================================
write_data      final_${{label}}.data
write_restart   final_${{label}}.restart
print "========== ${{label}} Complete =========="
"""


def _render_reaxff(build, state):
    """ReaxFF input script: 3-stage (minimize -> eq -> oxidation)."""
    s = state
    ff = s.ff
    names = get_filenames(s)

    # Determine FF version number for label
    ff_version = '2010' if s.forcefield == 'reaxff2010' else '2015'

    return f"""\
# ===================================================================
# Fe Slab + O2 Oxidation — ReaxFF
# Generated by lammps-pre v{VERSION}
# ===================================================================
#
# Usage:
#   lmp -var T {s.temperature} -var FF {ff_version} -var SEED {s.velocity_seed} -in {names['input']}
#
# Reference: {ff['reference']}
# ===================================================================

# --- Default variables (overridable via command line) ---
variable        T       index {s.temperature}
variable        FF      index {ff_version}
variable        SEED    index {s.velocity_seed}
variable        EQ_PS   index {s.get_eq_ps()}
variable        OX_PS   index {s.get_ox_ps()}

# --- Derived variables ---
variable        dt      equal {ff['dt']}
variable        T_damp  equal 100.0*${{dt}}
variable        eq_steps equal round(${{EQ_PS}}*1000/${{dt}})
variable        ox_steps equal round(${{OX_PS}}*1000/${{dt}})

variable        label   string reaxff${{FF}}_${{T}}K

# --- Force field file selection ---
variable        ffield string ffield.reax.Fe_O_C_H
if "${{FF}} == 2015" then &
    "variable ffield string ffield.reax.Shin2015"

# ===================================================================
# Basic Settings
# ===================================================================
units           real
atom_style      charge
boundary        {s.boundary}

read_data       {names['data']}

pair_style      {ff['pair_style']}
pair_coeff      * * ${{ffield}} Fe O

fix             qeq all qeq/reaxff 10 0.0 10.0 1.0e-6 reaxff

neighbor        2.0 bin
neigh_modify    every 1 delay 0 check yes

# ===================================================================
# Region Definitions
# ===================================================================
include         {names['regions']}

region          r_fixed block INF INF INF INF INF ${{z_fixed_top}}
group           g_fixed region r_fixed
group           g_mobile subtract all g_fixed

group           g_fe type 1
group           g_o  type 2

region          r_lower_nvt block INF INF INF INF ${{z_fixed_top}} ${{z_lower_nvt_top}}
region          r_nve block INF INF INF INF ${{z_lower_nvt_top}} ${{z_nve_top}}
region          r_upper_nvt block INF INF INF INF ${{z_wall_lower}} INF

group           g_lower_nvt region r_lower_nvt
group           g_nve region r_nve
group           g_upper_nvt region r_upper_nvt

# --- Walls ---
fix             wall_upper all wall/reflect zhi EDGE
fix             wall_lower_o g_o wall/reflect zlo v_z_wall_lower

# --- Frozen layer ---
velocity        g_fixed set 0.0 0.0 0.0
fix             freeze g_fixed setforce 0.0 0.0 0.0

# --- Diagnostics ---
compute         temp_mobile g_mobile temp
compute         o_z g_o property/atom z
compute         o_z_min g_o reduce min c_o_z
compute         o_z_max g_o reduce max c_o_z

# --- Output ---
thermo          {s.get_thermo_interval()}
thermo_style    custom {ff['thermo_fields']}
thermo_modify   temp temp_mobile
log             ${{label}}.log

dump            traj all custom {s.get_dump_interval()} traj_${{label}}.lammpstrj &
                {ff['dump_fields']}
dump_modify     traj sort id format float %12.6f

# ===================================================================
# Stage 1: Energy Minimization
# ===================================================================
print "========== Stage 1: Energy Minimization =========="
min_style       cg
minimize        {ff['min_etol']:.0e} {ff['min_ftol']:.0e} {ff['min_maxiter']} {ff['min_maxeval']}

# ===================================================================
# Stage 2: Equilibration (${{EQ_PS}} ps)
# ===================================================================
print "========== Stage 2: Equilibration (${{EQ_PS}} ps at ${{T}} K) =========="
timestep        ${{dt}}
velocity        g_mobile create ${{T}} ${{SEED}} dist gaussian

fix             nvt_lower g_lower_nvt nvt temp ${{T}} ${{T}} ${{T_damp}}
fix             nve_middle g_nve nve
fix             nvt_upper g_upper_nvt nvt temp ${{T}} ${{T}} ${{T_damp}}

run             ${{eq_steps}}

# ===================================================================
# Stage 3: Oxidation (${{OX_PS}} ps)
# ===================================================================
print "========== Stage 3: Oxidation (${{OX_PS}} ps at ${{T}} K) =========="
unfix           wall_lower_o
run             ${{ox_steps}}

# ===================================================================
# Save
# ===================================================================
write_data      final_${{label}}.data
write_restart   final_${{label}}.restart
print "========== ${{label}} Complete =========="
"""


# ═══════════════════════════════════════════════════════════════
# PBS Run Script Renderer
# ═══════════════════════════════════════════════════════════════

def render_run_script(build, state):
    """Render PBS job submission script."""
    s = state
    ff = s.ff
    names = get_filenames(s)
    ncpus = s.get_ncpus()
    mem = s.get_memory_gb()
    wt = s.get_walltime_hr()
    job_name = s.get_job_name()

    # Required files list
    required = [names['data'], names['regions']]
    if ff.get('potential_file'):
        required.append(ff['potential_file'])
    required_str = ' '.join(required)

    # LAMMPS command-line variables
    if s.forcefield == 'ace':
        lammps_vars = f'-var T {s.temperature} -var SEED {s.velocity_seed}'
    elif s.forcefield == 'reaxff2010':
        lammps_vars = f'-var T {s.temperature} -var FF 2010'
    elif s.forcefield == 'reaxff2015':
        lammps_vars = f'-var T {s.temperature} -var FF 2015'
    else:
        lammps_vars = f'-var T {s.temperature}'

    modules_str = ' '.join(s.modules)

    return f"""\
#!/bin/bash
#PBS -N {job_name}
#PBS -q {s.queue}
#PBS -l select=1:ncpus={ncpus}:mpiprocs={ncpus}:mem={mem}gb
#PBS -l walltime={wt}:00:00
#PBS -j oe
#PBS -o pbs_output.log
lammps_input_script="{names['input']}"
required_files="{required_str}"
LAMMPS_VARS="{lammps_vars}"
CurrDir="${{PBS_O_WORKDIR:-$(pwd)}}"
JOBID="${{PBS_JOBID:-local_$$}}"
RUNLOG="$CurrDir/run.log"
exec > >(tee -a "$RUNLOG") 2>&1
echo "=== 1. Environment ==="
echo "Start: $(date)"
echo "Host: $(hostname)"
echo "Dir: $CurrDir"
echo "Job ID: $JOBID"
source /etc/profile.d/modules.sh 2>/dev/null || true
module purge 2>/dev/null
module load {modules_str} 2>/dev/null || echo "Warning: module load failed"
export OMPI_CC=/app1/centos7/gnu/gcc-9.2.0/bin/gcc
export OMPI_CXX=/app1/centos7/gnu/gcc-9.2.0/bin/g++
export OMPI_FC=/app1/centos7/gnu/gcc-9.2.0/bin/gfortran
export PATH="${{HOME}}/local/lammps/bin:${{HOME}}/local/bin:$PATH"
export OMP_NUM_THREADS=1
export LD_LIBRARY_PATH="/app1/centos7/gnu/gcc-9.2.0/lib64:/usr/lib64:${{LD_LIBRARY_PATH}}"
LAMMPS_EXECUTABLE="{s.lammps_bin}"
if [ ! -x "$LAMMPS_EXECUTABLE" ]; then
    LAMMPS_EXECUTABLE=$(which lmp 2>/dev/null || which lmp_mpi 2>/dev/null)
    if [ -z "$LAMMPS_EXECUTABLE" ]; then echo "Error: LAMMPS not found"; exit 1; fi
fi
echo "LAMMPS: $LAMMPS_EXECUTABLE"
echo "=== File Check ==="
MISSING=0
for file in $lammps_input_script $required_files; do
    if [ -f "$CurrDir/$file" ]; then echo "  OK: $file"; else echo "  MISSING: $file"; MISSING=1; fi
done
if [ $MISSING -eq 1 ]; then echo "Error: required files missing"; exit 1; fi
if [ -f "$PBS_NODEFILE" ]; then NPROCS=$(wc -l < "$PBS_NODEFILE"); else NPROCS=${{NCPUS:-{ncpus}}}; fi
echo "Input: $lammps_input_script | Cores: $NPROCS"
echo "=== 2. Scratch ==="
tdir="${{LKPR_SCRATCH:-/hpctmp/$USER/$JOBID}}"
scratch_error() {{
    echo "Error: $1"
    echo "Scratch kept for manual recovery (if created): $tdir"
    exit 1
}}
case "$tdir" in
    /*) ;;
    *) scratch_error "scratch path must be absolute" ;;
esac
mkdir -p "$(dirname -- "$tdir")" || scratch_error "cannot create scratch parent: $tdir"
# Never mix this run with stale results or follow an existing scratch symlink.
mkdir -- "$tdir" || scratch_error "cannot create fresh scratch directory: $tdir"
cp "$CurrDir/$lammps_input_script" "$tdir/" || scratch_error "cannot stage input"
for file in $required_files; do
    cp "$CurrDir/$file" "$tdir/" || scratch_error "cannot stage required file: $file"
done
cd "$tdir" || scratch_error "cannot enter scratch directory"
echo "=== 3. LAMMPS Run: $(date) ==="
mpirun -np "$NPROCS" "$LAMMPS_EXECUTABLE" $LAMMPS_VARS -in "$lammps_input_script"
EXIT_CODE=$?
echo "=== LAMMPS Done: $(date) | exit=$EXIT_CODE ==="
echo "=== 4. Copy Results ==="
if [ $EXIT_CODE -eq 0 ]; then
    DEST="$CurrDir"
else
    DEST="$CurrDir/failed_${{JOBID}}"
fi
COPY_OK=0
if mkdir -p "$DEST"; then
    if cp -a "$tdir"/. "$DEST"/; then COPY_OK=1; fi
fi
if [ $COPY_OK -ne 1 ]; then
    echo "Error: failed to copy results to $DEST"
    echo "Scratch kept for manual recovery: $tdir"
    if [ $EXIT_CODE -eq 0 ]; then exit 1; else exit $EXIT_CODE; fi
fi
cd "$CurrDir" || scratch_error "cannot leave scratch directory after copying results"
if ! rm -rf -- "$tdir"; then
    echo "Error: scratch cleanup incomplete; inspect retained path: $tdir"
    exit 1
fi
if [ $EXIT_CODE -eq 0 ]; then
    echo "Success: results copied to $DEST"
else
    echo "Failed: results copied to $DEST"
fi
echo "=== Complete: $(date) ==="
exit $EXIT_CODE
"""
